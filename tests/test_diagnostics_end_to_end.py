"""Execute production C paths, then inspect the actual exported support ZIP."""
import importlib.util,json,pathlib,subprocess,sys,tempfile,time,unittest,zipfile
ROOT=pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'helper'))
import diagnostics
from test_http_diagnostics_native import build_probe

class ExportEndToEndTests(unittest.TestCase):
 def test_native_producer_to_zip(self):
  with tempfile.TemporaryDirectory() as tmp:
   root=pathlib.Path(tmp);home=root/'private';now=int(time.time())
   diagnostics.start(home,now)
   binary=build_probe(root)
   http=subprocess.run([str(binary),'--emit-fixture'],capture_output=True,text=True,check=True).stdout
   token=root/'token'
   subprocess.run(['clang','-O1','-g','-fsanitize=address,undefined',str(ROOT/'tests/token_diagnostics_probe.c'),'-o',str(token)],check=True,capture_output=True)
   runtime=subprocess.run([str(token)],capture_output=True,text=True,check=True).stdout
   # The curl harness replaces the OS writer; add its deterministic process
   # envelope here. All diagnostic fields below were generated by production C.
   http=''.join('[t=1792641840000 p=123 th=7] '+line+'\n' for line in http.splitlines())
   (home/'http.log').write_text(http)
   (home/'runtime.log').write_text(runtime)
   (home/'session.bin').write_text('SYNTHETIC_PRIVATE_SESSION')
   target=root/'export.zip';diagnostics.export(home,target,now+1)
   with zipfile.ZipFile(target) as z:
    all_data=b'\n'.join(z.read(n) for n in z.namelist()).decode()
    for secret in ('SENTINEL','SYNTHETIC_CREDENTIAL','SYNTHETIC_PRIVATE_SESSION','PRIVATE_QUERY','PRIVATE_ID','PRIVATE_HOST'):
     self.assertNotIn(secret,all_data)
    http=z.read('logs/http.log').decode();runtime=z.read('logs/runtime.log').decode()
    for value in ('host=profile.xboxlive.com','operation=profile','http=401','error=InvalidToken','request_id=12345678-1234-1234-1234-123456789abc'):
     self.assertIn(value,http)
    self.assertIn('error=BadRequest',http)
    self.assertIn('signature=absent',runtime)
    self.assertIn('refresh=1',runtime)
    self.assertIn('hr=80190191',runtime)
    coverage=json.loads(z.read('manifest.json'))['diagnostic_coverage']
    self.assertEqual(coverage['http_sources']['curl']['status'],'observed')
    self.assertEqual(coverage['layers']['token']['status'],'observed')
    self.assertEqual(coverage['layers']['http']['missing_terminal_identities'],0)
    self.assertEqual(coverage['layers']['token']['missing_terminal_identities'],0)
    self.assertEqual(coverage['uncorrelated_native_failure_observations'],1)
    self.assertEqual(coverage['http_sources']['native-http']['status'],'unobserved')
if __name__=='__main__':unittest.main()
